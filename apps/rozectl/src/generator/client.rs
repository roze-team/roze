pub fn render_ts_client(spec: &ApiSpec) -> String {
    let mut out =
        String::from("/* eslint-disable */\n// Generated by rozectl. Do not edit by hand.\n\n");
    out.push_str("export interface RequestOptions {\n");
    out.push_str("  baseUrl?: string;\n");
    out.push_str("  headers?: Record<string, string>;\n");
    out.push_str("  fetch?: typeof fetch;\n");
    out.push_str("}\n\n");

    for ty in &spec.types {
        out.push_str(&render_interface(ty));
        out.push('\n');
    }

    out.push_str(
        "async function requestJson<T>(method: string, path: string, query: Record<string, unknown>, body: unknown, headers: Record<string, string>, options: RequestOptions): Promise<T> {\n",
    );
    out.push_str("  const fetchImpl = options.fetch ?? fetch;\n");
    out.push_str("  const baseUrl = (options.baseUrl ?? '').replace(/\\/$/, '');\n");
    out.push_str("  const params = new URLSearchParams();\n");
    out.push_str("  for (const [key, value] of Object.entries(query)) {\n");
    out.push_str(
        "    if (value !== undefined && value !== null) params.append(key, String(value));\n",
    );
    out.push_str("  }\n");
    out.push_str("  const qs = params.toString();\n");
    out.push_str("  const url = `${baseUrl}${path}${qs ? `?${qs}` : ''}`;\n");
    out.push_str("  const requestHeaders: Record<string, string> = { ...(options.headers ?? {}), ...headers };\n");
    out.push_str("  const init: RequestInit = { method, headers: requestHeaders };\n");
    out.push_str("  if (body !== undefined) {\n");
    out.push_str("    requestHeaders['content-type'] = requestHeaders['content-type'] ?? 'application/json';\n");
    out.push_str("    init.body = JSON.stringify(body);\n");
    out.push_str("  }\n");
    out.push_str("  const response = await fetchImpl(url, init);\n");
    out.push_str("  if (!response.ok) throw new Error(`HTTP ${response.status}: ${await response.text()}`);\n");
    out.push_str("  if (response.status === 204) return undefined as T;\n");
    out.push_str("  return await response.json() as T;\n");
    out.push_str("}\n\n");

    for route in &spec.rest_routes {
        out.push_str(&render_route_function(spec, route));
        out.push('\n');
    }

    out
}

